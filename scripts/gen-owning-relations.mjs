// Writes src/generated/owningRelations.ts: for each model, the relation fields
// that hold a foreign key on that model (those declared with
// `@relation(... fields: [...] ...)`). The tenant extension needs this to choose
// Prisma's checked or unchecked create input; Prisma 7's runtime DMMF no longer
// carries relationFromFields, so it is read from the schema here.
//
// Runs as part of `npm run prisma:generate`; test/owningRelations.test.ts fails
// if the committed file and the schema disagree.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function owningRelationsFromSchema(schema) {
  const result = {};
  const modelPattern = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
  for (const [, model, body] of schema.matchAll(modelPattern)) {
    const owning = [];
    for (const line of body.split(/\r?\n/)) {
      const field = line.match(/^\s+(\w+)\s+\w+\??\s+.*@relation\(([^)]*)\)/);
      if (field && /\bfields\s*:\s*\[/.test(field[2])) owning.push(field[1]);
    }
    result[model] = owning.sort();
  }
  return result;
}

export function renderOwningRelations(map) {
  const lines = Object.keys(map).sort().map((model) => `  ${model}: [${map[model].map((f) => `'${f}'`).join(', ')}],`);
  return `// Generated by scripts/gen-owning-relations.mjs from prisma/schema.prisma. Do not edit.\nexport const OWNING_RELATIONS: Record<string, readonly string[]> = {\n${lines.join('\n')}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const schema = readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8');
  mkdirSync(path.join(root, 'src/generated'), { recursive: true });
  writeFileSync(path.join(root, 'src/generated/owningRelations.ts'), renderOwningRelations(owningRelationsFromSchema(schema)));
}
